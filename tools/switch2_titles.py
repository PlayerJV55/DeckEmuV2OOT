# Regenerates dist/switch2_titles.json, the bundled program ID -> name table used for Switch 2
# dumps without control data, from the Switchbrew wiki's Switch 2 title list.
# Title list data courtesy of the Switchbrew contributors: https://switchbrew.org
#
# Usage: switch2_titles.py [--input page.wiki] [--output dist/switch2_titles.json]

import argparse
import html
import json
import os
import re
import sys
import urllib.request

PAGE = "https://switchbrew.org/wiki/Switch_2:_Title_list/Games"
RAW_URL = "https://switchbrew.org/w/index.php?title=Switch_2:_Title_list/Games&action=raw"

# Rows the wiki gets wrong: 04007C6028AA8000 is listed twice, but it is the Yoshi demo.
DROPPED_ROWS = {
    ("04007C6028AA8000", "Nintendo Switch Sports Resort"),
}

# Titles whose box art is named after another title.
COVERS = {
    "04007C6028AA8000": "yoshi-and-the-mysterious-book",
}

ROW = re.compile(r"^\|\s*(04[0-9A-Fa-f]{14})\s*\|\|(.*)$")


def clean_name(text):
    text = re.sub(r"<ref[^>]*/>|<ref[^>]*>.*?</ref>", "", text, flags=re.S)
    text = re.sub(r"<br\s*/?>", " ", text, flags=re.I)
    text = re.sub(r"<[^>]+>", "", text)
    # Innermost templates first, so nested ones go too.
    while re.search(r"\{\{[^{}]*\}\}", text):
        text = re.sub(r"\{\{[^{}]*\}\}", "", text)
    text = re.sub(r"\[\[(?:[^|\]]*\|)?([^\]]*)\]\]", r"\1", text)
    text = re.sub(r"\[(?:https?:)?//\S+\s+([^\]]*)\]", r"\1", text)
    text = re.sub(r"'{2,}", "", text)
    text = html.unescape(text)
    return re.sub(r"\s+", " ", text).strip()


def parse_titles(wikitext):
    titles = {}
    for line in wikitext.splitlines():
        match = ROW.match(line)
        if match is None:
            continue
        program_id = match.group(1).upper()
        name = clean_name(match.group(2).split("||")[0])
        if not name or (program_id, name) in DROPPED_ROWS:
            continue
        if program_id in titles:
            if titles[program_id] != name:
                print(f"warning: {program_id} listed as both {titles[program_id]!r} and "
                      f"{name!r}, keeping the first", file=sys.stderr)
            continue
        titles[program_id] = name
    return titles


def to_json(titles):
    out = {
        "_source": f"Generated by tools/switch2_titles.py from the Switchbrew wiki ({PAGE}). "
                   "Thanks to the Switchbrew contributors."
    }
    for program_id in sorted(titles):
        name = titles[program_id]
        cover = COVERS.get(program_id)
        out[program_id] = {"name": name, "cover": cover} if cover else name
    return json.dumps(out, ensure_ascii=False, indent=4) + "\n"


def main():
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser = argparse.ArgumentParser(description="Regenerate the bundled Switch 2 title list.")
    parser.add_argument("--input", help="read the wikitext from a file instead of Switchbrew")
    parser.add_argument("--output", default=os.path.join(root, "dist", "switch2_titles.json"))
    args = parser.parse_args()

    if args.input:
        with open(args.input, encoding="utf-8") as f:
            wikitext = f.read()
    else:
        request = urllib.request.Request(RAW_URL, headers={"User-Agent": "switch2_titles.py"})
        with urllib.request.urlopen(request, timeout=30) as response:
            wikitext = response.read().decode("utf-8")

    titles = parse_titles(wikitext)
    if not titles:
        sys.exit("error: no title rows found, did the page layout change?")

    with open(args.output, "w", encoding="utf-8") as f:
        f.write(to_json(titles))
    print(f"Wrote {len(titles)} titles to {args.output}")


if __name__ == "__main__":
    main()
